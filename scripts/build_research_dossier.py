def write_inventory():
    paths = set(p for p in (ROOT/'docs').glob('*') if p.suffix in {'.md','.csv'} and p.name not in EXCLUDED_DOCS)
    paths.update(ROOT.glob('*.md'))
    paths.update(p for p in (ROOT/'audit').glob('*.json') if p.name != 'journal_dossier_20261108.json')
    for folder in ['scripts','src','tests','kaggle_event_sequence_gru']:
        paths.update(p for p in (ROOT/folder).rglob('*') if p.suffix in {'.py','.ipynb','.md'} and '__pycache__' not in p.parts)
    paths.update(p for p in MANUSCRIPT.glob('*') if p.suffix in {'.md','.py','.bib','.csv','.json','.tex','.pdf','.docx'} and p.name!='research_document_inventory.csv')
    paths.update((MANUSCRIPT/'reviews').glob('*.md'))
    paths={p for p in paths if p.is_file()}
    rows=[]
    for p in sorted(paths):
        rel=p.relative_to(ROOT).as_posix()
        if rel.startswith('docs/') or p.parent == ROOT:
            kind='research_source_document'
        elif rel.startswith('audit/'):
            kind='top_level_aggregate_audit'
        elif '/reviews/' in rel:
            kind='internal_review'
        elif p.suffix=='.py':
            kind='implementation_reference'
        elif p.suffix=='.ipynb':
            kind='notebook_reference'
        else:
            kind='manuscript_or_supporting_artifact'
        rows.append({'path':rel,'class':kind,'status':'current_document' if rel in CURRENT_DOCS else 'source_or_historical_reference',
                     'title':title(p) if p.suffix=='.md' else p.stem,'bytes':p.stat().st_size,'sha256':sha(p)})
    with (MANUSCRIPT/'research_document_inventory.csv').open('w',newline='') as stream:
        writer=csv.DictWriter(stream,fieldnames=list(rows[0]),lineterminator='\n');writer.writeheader();writer.writerows(rows)
    require(all(f'docs/{p.name}' in {r['path'] for r in rows} for p in (ROOT/'docs').glob('*.md') if p.name not in EXCLUDED_DOCS),'Unindexed research document')
    require(all(sha(ROOT/r['path']) == r['sha256'] for r in rows), 'Inventory source hash mismatch')
    return rows


def compile_pdf(path):
    return run(['tectonic','--only-cached','--keep-logs','--outdir',str(path.parent),path.name],cwd=path.parent)


def export_document(module, path):
    # Export into a temporary folder so the shared renderer cannot overwrite the main paper.
    with tempfile.TemporaryDirectory(prefix='t1d-doc-export-',dir=MANUSCRIPT) as folder:
        temp=Path(folder); old=module.HERE;module.HERE=temp
        document=list(module.blocks(path.read_text()))
        try:
            for kind,value in document:
                if kind=='image':
                    target=temp/value[1];target.parent.mkdir(parents=True,exist_ok=True)
                    shutil.copy2(path.parent/value[1],target)
            module.write_tex(document);module.write_docx(document)
            tex=(temp/'manuscript.tex').read_text().replace('Temporal event graphs for hypoglycemia prediction','T1D research documentation')
            (temp/'manuscript.tex').write_text(tex)
            compile_pdf(temp/'manuscript.tex')
            for suffix in ['tex','pdf','docx']:
                shutil.copy2(temp/f'manuscript.{suffix}',path.with_suffix('.'+suffix))
        finally:
            module.HERE=old
    return {'path':path.relative_to(ROOT).as_posix(),'pdf_bytes':path.with_suffix('.pdf').stat().st_size}


def plain(value):
    value=re.sub(r'\[([^\]]+)\]\([^)]+\)',r'\1',value)
    return re.sub(r'[*`#]','',value)


def words(value):
    return len(plain(value).split())


def verify_documents(module):
    text=(MANUSCRIPT/'manuscript.md').read_text()
    abstract=text.split('## Abstract',1)[1].split('Keywords:',1)[0]
    body=text.split('## 1. Background',1)[1].split('## References',1)[0]
    paragraphs=' '.join(value for kind,value in module.blocks(body) if kind=='paragraph')
    legends=text.split('## Figure legends',1)[1]
    counts={'abstract_with_labels':words(abstract),'conservative_main_declarations_legends':words(paragraphs+' '+legends),
            'main_tables':len(re.findall(r'^\*\*Table \d+\.',text,re.M)),
            'figures':len(re.findall(r'^!\[',text,re.M)),
            'keywords':len(text.split('Keywords:',1)[1].split('\n',1)[0].split(';'))}
    require(counts['abstract_with_labels']<=250,'Abstract exceeds250words')
    require(counts['conservative_main_declarations_legends']<=4000,'Main text exceeds4000words')
    require(counts['main_tables']<=4 and counts['figures']<=6 and counts['keywords']<=5,'Journal display limit exceeded')
    required=['Objective','Materials and Methods','Results','Discussion','Conclusion']
    require(re.findall(r'\*\*([^:]+):\*\*',abstract)==required,'Wrong abstract headings')
    refs=text.split('## References',1)[1].split('## Figure legends',1)[0]
    labels=[int(x) for x in re.findall(r'^\[(\d+)\]',refs,re.M)]
    citations=[int(x) for group in re.findall(r'\[([\d,]+)\]',text.split('## References')[0]) for x in group.split(',')]
    first=list(dict.fromkeys(citations))
    require(labels==first==list(range(1,len(labels)+1)),'Citation ordering or coverage mismatch')
    require('{{' not in text,'Unresolved result placeholder')
    require('Pronab Chandra Roy; Lihui Liu' in text,'Supplied author names missing')
    require('No institutional affiliations declared.' in text,'Affiliation declaration mismatch')
    broken=[]
    for rel in ['manuscript/manuscript.md']+CURRENT_DOCS:
        path=ROOT/rel
        for dest in re.findall(r'\]\(([^)]+)\)',path.read_text()):
            if dest.startswith(('https:','http:','mailto:','#')):continue
            target=unquote(dest.strip('<>').split('#')[0])
            if target and not (path.parent/target).exists():broken.append({'source':rel,'target':dest})
    require(not broken,f'Broken current-document links: {broken}')
    for path in [MANUSCRIPT/'manuscript.docx']+[ROOT/r.replace('.md','.docx') for r in EXPORT_DOCS]:
        with zipfile.ZipFile(path) as archive:
            require(archive.testzip() is None,f'DOCX corruption: {path}')
            for name in archive.namelist():
                if name.endswith(('.xml','.rels')):ET.fromstring(archive.read(name))
    with zipfile.ZipFile(MANUSCRIPT/'manuscript.docx') as archive:
        require(b'w:line="480"' in archive.read('word/styles.xml'),'Main DOCX is not double spaced')
        doc = ET.fromstring(archive.read('word/document.xml'))
        image_ids = [node.attrib['id'] for node in doc.findall('.//{*}docPr')]
        require(len(image_ids) == len(set(image_ids)), 'Duplicate DOCX image identifiers')
        for table in doc.findall('.//{*}tbl'):
            columns = len(table.find('{*}tblGrid'))
            require(all(len(row.findall('{*}tc')) == columns for row in table.findall('{*}tr')),
                    'DOCX table grid mismatch')
    pdf_text=run(['pdftotext',str(MANUSCRIPT/'manuscript.pdf'),'-'])
    collapsed=' '.join(pdf_text.split()).replace('−','-')
    require('Pronab Chandra Roy' in collapsed and 'Lihui Liu' in collapsed,'PDF author text mismatch')
    require('0.009900' in collapsed and '1,296,297' in collapsed,'PDF current result text missing')
    pdf_pages = {}
    for pdf in [MANUSCRIPT/'manuscript.pdf'] + [(ROOT/r).with_suffix('.pdf') for r in EXPORT_DOCS]:
        require(pdf.stat().st_size > 1000, 'Missing PDF export')
        result = subprocess.run(['pdftotext', '-bbox', str(pdf), '-'],
                                capture_output=True, text=True, check=True)
        layout = ET.fromstring(result.stdout)
        pages = layout.findall('.//{*}page')
        for number, page in enumerate(pages, 1):
            width = float(page.attrib['width'])
            require(all(float(word.attrib['xMin']) >= 15 and float(word.attrib['xMax']) <= width-15
                        for word in page.findall('.//{*}word')),
                    f'PDF text runs outside page edges: {pdf.name}, page {number}')
        pdf_pages[pdf.relative_to(ROOT).as_posix()] = len(pages)
    return counts|{'references':len(labels),'broken_local_links':broken,'docx_xml':'passed','pdf_text':'passed',
                   'pdf_page_edge_checks':'passed','pdf_pages':pdf_pages}


def package(inventory, audit):
    novelty=load_module('novelty_packager',ROOT/'scripts/build_novelty_review_package.py')
    files=set(novelty.BASE_FILES)
    files.update(r['path'] for r in inventory if r['class']=='research_source_document')
    files.update(CURRENT_DOCS)
    files.update(['manuscript/research_document_inventory.csv','audit/journal_dossier_20261108.json',
                  'scripts/build_research_dossier.py','pyproject.toml'])
    files.update(p.relative_to(ROOT).as_posix() for p in (MANUSCRIPT/'figures').glob('*') if p.suffix in {'.png','.pdf','.svg'})
    for rel in EXPORT_DOCS+['manuscript/manuscript.md']:
        files.update(str(Path(rel).with_suffix('.'+s)) for s in ['pdf','docx','tex'])
    em=json.loads((MANUSCRIPT/'evidence_map.json').read_text())
    files.update(em['paired_audits']);files.update(em['methods_sources'])
    files.update(em['supporting_documents'])
    files.add('README.md')
    require(all((ROOT/name).is_file() for name in files),'Missing package source')
    for name in files:
        require(not Path(name).parts[0] in {'data','private'},f'Protected path in package: {name}')
        if name.endswith('.json'):
            novelty.reject_private_or_holdout_content(json.loads((ROOT/name).read_text()),name)
    out=ROOT/'research_outputs/journal_documentation_20261108.zip';out.parent.mkdir(exist_ok=True)
    manifest=[]
    with zipfile.ZipFile(out,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=6) as archive:
        readme='# Journal documentation dossier\n\nStart with [the reading guide](manuscript/START_HERE.md). '
        readme+='Includes the current paper, complete research record, supplements, three internal agent reviews, ratings, revision responses and readiness register. '
        readme+='Documentation revision8November2026; empirical cutoff31October2026. Author declarations and empirical gaps remain visible. '
        readme+='No raw clinical data or private prediction/checkpoint files are included.\n'
        archive.writestr('README_DOSSIER.md',readme)
        manifest.append({'path':'README_DOSSIER.md','bytes':len(readme.encode()),'sha256':hashlib.sha256(readme.encode()).hexdigest()})
        for name in sorted(files):
            data=(ROOT/name).read_bytes();archive.writestr(name,data)
            manifest.append({'path':name,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()})
        archive.writestr('MANIFEST.json',json.dumps({'documentation_date':DATE,'empirical_cutoff':'2026-10-31','files':manifest},indent=2)+'\n')
    with zipfile.ZipFile(out) as archive:
        require(archive.testzip() is None,'Bundle ZIP corruption')
        for row in manifest:
            require(hashlib.sha256(archive.read(row['path'])).hexdigest()==row['sha256'],'Manifest hash mismatch')
    receipt={'package':out.relative_to(ROOT).as_posix(),'bytes':out.stat().st_size,'sha256':sha(out),
             'members':len(manifest)+1,'integrity':'passed','document_inventory_rows':len(inventory),
             'documentation_checks':audit['document_checks'],'submission_ready':False,
             'remaining_author_facts':'see manuscript/author_declarations.md',
             'scope':'Internal documentation verification; no new empirical validation or journal acceptance claim.'}
    (out.parent/'journal_documentation_20261108_receipt.json').write_text(json.dumps(receipt,indent=2)+'\n')
    return receipt


def main():
    run([sys.executable,str(MANUSCRIPT/'build_manuscript.py')])
    compile_pdf(MANUSCRIPT/'manuscript.tex')
    module=load_module('manuscript_renderer',MANUSCRIPT/'build_manuscript.py')
    supplementary_results();write_guide()
    exports=[export_document(module,ROOT/rel) for rel in EXPORT_DOCS]
    inventory=write_inventory()
    checks=verify_documents(module)
    missing_raw=[str(p.relative_to(ROOT)) for p in [ROOT/'data/Loop study public dataset 2023-01-31/Data Tables/LOOPDeviceBasal1.txt',ROOT/'data/Loop study public dataset 2023-01-31/Data Tables/LOOPDeviceBasal2.txt'] if not p.exists()]
    audit={'date':DATE,'empirical_cutoff':'2026-10-31','audit_type':'research documentation and journal-format verification',
           'identifiers_emitted':False,'locked_holdout_used':False,'status':'passed_for_documentation_scope',
           'document_checks':checks,'exports':exports,'inventory_classes':dict(Counter(r['class'] for r in inventory)),
           'missing_raw_rebuild_prerequisites':missing_raw,
           'author_names_supplied':['Pronab Chandra Roy','Lihui Liu'],'affiliations':'None declared by user',
           'journal_format':'JAMIA Research and Applications','submission_ready':False,
           'limitations':['Author ethics/funding/interests/contributions/PPI/contact and release facts remain unconfirmed.',
                         'Analytic population characterization and claim-dependent empirical analyses remain incomplete.',
                         'Document checks do not establish clinical validity, risk-of-bias clearance or journal acceptance.',
                         'Three AI-agent reviews are internal assistance, not independent human peer review.',
                         'Current rendering inspected separately; historical documents retain superseded statements.']}
    (ROOT/'audit/journal_dossier_20261108.json').write_text(json.dumps(audit,indent=2)+'\n')
    print(json.dumps(package(inventory,audit),indent=2))


if __name__=='__main__':main()
