def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run(command, cwd=ROOT):
    result = subprocess.run(command, cwd=cwd, capture_output=True, text=True,
                            env={**os.environ, 'MPLCONFIGDIR': '/private/tmp/t1d-manuscript-matplotlib'})
    require(result.returncode == 0, f'Build failed: {command}\n{result.stdout}\n{result.stderr}')
    return result.stdout + result.stderr


def title(path):
    for line in path.read_text(errors='replace').splitlines():
        if line.startswith('# '):
            return line[2:].strip()
    return path.stem


def supplementary_results():
    with (MANUSCRIPT/'results_snapshot.csv').open(newline='') as stream:
        rows = list(csv.DictReader(stream))
    parts = ['# Supplementary numerical results',
      '\nRevision: 8 November 2026. Saved evidence through 31 October 2026. '
      'This appendix includes all 21 central paired comparisons. It is not a count of every historical fit. '
      'The full-precision [CSV](results_snapshot.csv) and [evidence map](evidence_map.json) preserve source links. '
      'Differences are graph minus the paired comparator; intervals condition on fixed fitted predictions. '
      'AP uses positive-outcome participants and macro-Brier uses all participants. '
      'No numerical result is regenerated by training in this documentation build.\n']
    labels = {'graph_vs_late_fusion_sequence': 'Earlier graph versus late-fusion sequence; one epoch',
              'graph_vs_time_aligned_nongraph': 'Graph versus time-aligned pooling; two epochs',
              'graph_vs_time_aligned_nongraph_8_epoch_cpu': 'Graph versus pooling; eight-epoch CPU follow-up'}
    for comparison in labels:
        for seed in sorted({r['training_seed'] for r in rows if r['comparison'] == comparison}):
            group = [r for r in rows if r['comparison'] == comparison and r['training_seed'] == seed]
            parts.append(f'\n## {labels[comparison]}, seed {seed}\n')
            parts.append('| Fold | Graph AP | Comparator AP | AP difference (95% interval) | Macro-Brier difference (95% interval) |\n|---|---:|---:|---|---|')
            for r in group:
                f=lambda key: f'{float(r[key]):+.6f}'
                parts.append(f"| {r['fold']} | {float(r['graph_macro_ap']):.6f} | {float(r['sequence_macro_ap']):.6f} | {f('ap_difference')} [{f('ap_ci_low')}, {f('ap_ci_high')}] | {f('brier_difference')} [{f('brier_ci_low')}, {f('brier_ci_high')}] |")
            parts.append('\n| Fold | Graph macro-Brier | Comparator macro-Brier | AP-defined / all participants |\n|---|---:|---:|---|')
            for r in group:
                parts.append(f"| {r['fold']} | {float(r['graph_macro_brier']):.6f} | {float(r['sequence_macro_brier']):.6f} | {r['ap_defined_participants']} / {r['participants']} |")
            parts.append('\nPaired audit sources: '+', '.join(f"[{r['fold']}](../{r['source']})" for r in group)+'.\n')
    summary = json.loads((ROOT/'audit/loop_graph_vs_aligned_nongraph_two_seed_five_fold_participant_summary.json').read_text())
    ap=summary['participant_macro_ap_difference']; bs=summary['participant_macro_brier_difference']
    parts.append('\n## Two-seed participant summary\n')
    parts.append('Each participant\'s paired effects were averaged across the two fixed seeds before participant resampling. '
                 'This differs from averaging fold APs and does not make the seeds independent cohorts. '
                 f"The mean AP difference was {ap['graph_minus_control_after_within_participant_seed_average']:.10f}, "
                 f"with interval {ap['fixed_prediction_participant_bootstrap_95_ci']}; "
                 f"macro-Brier difference was {bs['graph_minus_control_after_within_participant_seed_average']:.10f}, "
                 f"with interval {bs['fixed_prediction_participant_bootstrap_95_ci']}. "
                 '[Source summary](../audit/loop_graph_vs_aligned_nongraph_two_seed_five_fold_participant_summary.json).\n')
    parts.append('\n## Auxiliary evidence\n\nHistorical baseline, event-summary/residual, recovered GRU, routing, endpoint, event-age, event-input, '
                 'explanation and external-transfer evidence is itemized with source links and scope in the '
                 '[master research record](../docs/research_master_record_2026_11_08.md). '
                 'The [sequence comparison plot](figures/ap_differences.pdf) is a separate supplementary figure. '
                 'Those diagnostics are not pooled into this 21-pair numerical table.\n')
    (MANUSCRIPT/'supplementary_results.md').write_text('\n'.join(parts))
    return rows


